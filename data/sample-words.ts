const ROMAJI_BY_ID = new Map(
  SAMPLE_WORDS.map((word) => [word.id, toRomaji(word.reading)]),
);

export function getRomaji(word: Word) {
  return ROMAJI_BY_ID.get(word.id) ?? toRomaji(word.reading);
}

export function getWord(id: string | undefined) {
  return SAMPLE_WORDS.find((word) => word.id === id);
}
